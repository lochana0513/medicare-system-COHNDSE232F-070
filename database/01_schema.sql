SET DEFINE OFF

-- ---------------------------------------------------------------------
--  Drop existing objects (child tables first) so the script is re-runnable
-- ---------------------------------------------------------------------
BEGIN
    FOR t IN (SELECT table_name FROM user_tables
              WHERE table_name IN ('ERROR_LOG','APPOINTMENT_AUDIT','PAYMENT','PRESCRIPTION_ITEM',
                                   'CONSULTATION','APPOINTMENT','PATIENT',
                                   'DOCTOR_SCHEDULE','HOSPITAL','DOCTOR','SPECIALIZATION'))
    LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;
END;
/

-- ---------------------------------------------------------------------
--  SPECIALIZATION
-- ---------------------------------------------------------------------
CREATE TABLE specialization (
    specialization_id   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    name                VARCHAR2(60)  NOT NULL,
    description         VARCHAR2(250),
    CONSTRAINT pk_specialization      PRIMARY KEY (specialization_id),
    CONSTRAINT uq_specialization_name UNIQUE (name)
);

-- ---------------------------------------------------------------------
--  DOCTOR
-- ---------------------------------------------------------------------
CREATE TABLE doctor (
    doctor_id           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    specialization_id   NUMBER        NOT NULL,
    first_name          VARCHAR2(50)  NOT NULL,
    last_name           VARCHAR2(50)  NOT NULL,
    slmc_reg_no         VARCHAR2(15)  NOT NULL,
    email               VARCHAR2(100) NOT NULL,
    phone               VARCHAR2(15)  NOT NULL,
    consultation_fee    NUMBER(10,2)  NOT NULL,
    experience_years    NUMBER(2)     DEFAULT 0 NOT NULL,
    status              VARCHAR2(10)  DEFAULT 'ACTIVE' NOT NULL,
    CONSTRAINT pk_doctor              PRIMARY KEY (doctor_id),
    CONSTRAINT fk_doctor_spec         FOREIGN KEY (specialization_id)
                                      REFERENCES specialization (specialization_id),
    CONSTRAINT uq_doctor_slmc         UNIQUE (slmc_reg_no),
    CONSTRAINT uq_doctor_email        UNIQUE (email),
    CONSTRAINT ck_doctor_email        CHECK (REGEXP_LIKE(email, '^[^@ ]+@[^@ ]+\.[^@ ]+$')),
    CONSTRAINT ck_doctor_phone        CHECK (REGEXP_LIKE(phone, '^0[0-9]{9}$')),
    CONSTRAINT ck_doctor_fee          CHECK (consultation_fee > 0),
    CONSTRAINT ck_doctor_experience   CHECK (experience_years BETWEEN 0 AND 60),
    CONSTRAINT ck_doctor_status       CHECK (status IN ('ACTIVE','ON_LEAVE','INACTIVE'))
);

-- ---------------------------------------------------------------------
--  HOSPITAL
-- ---------------------------------------------------------------------
CREATE TABLE hospital (
    hospital_id         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    name                VARCHAR2(100) NOT NULL,
    address             VARCHAR2(200) NOT NULL,
    city                VARCHAR2(50)  NOT NULL,
    phone               VARCHAR2(15)  NOT NULL,
    email               VARCHAR2(100),
    CONSTRAINT pk_hospital            PRIMARY KEY (hospital_id),
    CONSTRAINT uq_hospital_name       UNIQUE (name),
    CONSTRAINT ck_hospital_phone      CHECK (REGEXP_LIKE(phone, '^0[0-9]{9}$')),
    CONSTRAINT ck_hospital_email      CHECK (email IS NULL OR REGEXP_LIKE(email, '^[^@ ]+@[^@ ]+\.[^@ ]+$'))
);

-- ---------------------------------------------------------------------
--  DOCTOR_SCHEDULE  (resolves the M:N between Doctor and Hospital)
--  Times are stored as 'HH24:MI' strings.
-- ---------------------------------------------------------------------
CREATE TABLE doctor_schedule (
    schedule_id         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    doctor_id           NUMBER        NOT NULL,
    hospital_id         NUMBER        NOT NULL,
    day_of_week         VARCHAR2(3)   NOT NULL,
    start_time          VARCHAR2(5)   NOT NULL,
    end_time            VARCHAR2(5)   NOT NULL,
    max_patients        NUMBER(3)     NOT NULL,
    CONSTRAINT pk_doctor_schedule     PRIMARY KEY (schedule_id),
    CONSTRAINT fk_schedule_doctor     FOREIGN KEY (doctor_id)   REFERENCES doctor (doctor_id),
    CONSTRAINT fk_schedule_hospital   FOREIGN KEY (hospital_id) REFERENCES hospital (hospital_id),
    CONSTRAINT uq_schedule_slot       UNIQUE (doctor_id, day_of_week, start_time),
    CONSTRAINT ck_schedule_day        CHECK (day_of_week IN ('MON','TUE','WED','THU','FRI','SAT','SUN')),
    CONSTRAINT ck_schedule_start      CHECK (REGEXP_LIKE(start_time, '^([01][0-9]|2[0-3]):[0-5][0-9]$')),
    CONSTRAINT ck_schedule_end        CHECK (REGEXP_LIKE(end_time,   '^([01][0-9]|2[0-3]):[0-5][0-9]$')),
    CONSTRAINT ck_schedule_times      CHECK (end_time > start_time),
    CONSTRAINT ck_schedule_max        CHECK (max_patients BETWEEN 1 AND 100)
);

-- ---------------------------------------------------------------------
--  PATIENT
-- ---------------------------------------------------------------------
CREATE TABLE patient (
    patient_id          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    first_name          VARCHAR2(50)  NOT NULL,
    last_name           VARCHAR2(50)  NOT NULL,
    nic                 VARCHAR2(12)  NOT NULL,
    date_of_birth       DATE          NOT NULL,
    gender              CHAR(1)       NOT NULL,
    phone               VARCHAR2(15)  NOT NULL,
    email               VARCHAR2(100),
    address             VARCHAR2(200),
    blood_group         VARCHAR2(3),
    registered_date     DATE          DEFAULT SYSDATE NOT NULL,
    CONSTRAINT pk_patient             PRIMARY KEY (patient_id),
    CONSTRAINT uq_patient_nic         UNIQUE (nic),
    CONSTRAINT uq_patient_email       UNIQUE (email),
    -- Sri Lankan NIC: old format 9 digits + V/X, new format 12 digits
    CONSTRAINT ck_patient_nic         CHECK (REGEXP_LIKE(nic, '^([0-9]{9}[VvXx]|[0-9]{12})$')),
    CONSTRAINT ck_patient_gender      CHECK (gender IN ('M','F','O')),
    CONSTRAINT ck_patient_phone       CHECK (REGEXP_LIKE(phone, '^0[0-9]{9}$')),
    CONSTRAINT ck_patient_email       CHECK (email IS NULL OR REGEXP_LIKE(email, '^[^@ ]+@[^@ ]+\.[^@ ]+$')),
    CONSTRAINT ck_patient_blood       CHECK (blood_group IS NULL OR
                                             blood_group IN ('A+','A-','B+','B-','AB+','AB-','O+','O-')),
    CONSTRAINT ck_patient_dob         CHECK (date_of_birth <= registered_date)
);

-- ---------------------------------------------------------------------
--  APPOINTMENT
-- ---------------------------------------------------------------------
CREATE TABLE appointment (
    appointment_id      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    patient_id          NUMBER        NOT NULL,
    schedule_id         NUMBER        NOT NULL,
    appointment_date    DATE          NOT NULL,
    queue_no            NUMBER(3)     NOT NULL,
    status              VARCHAR2(10)  DEFAULT 'BOOKED' NOT NULL,
    booked_at           TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    notes               VARCHAR2(250),
    CONSTRAINT pk_appointment         PRIMARY KEY (appointment_id),
    CONSTRAINT fk_appt_patient        FOREIGN KEY (patient_id)  REFERENCES patient (patient_id),
    CONSTRAINT fk_appt_schedule       FOREIGN KEY (schedule_id) REFERENCES doctor_schedule (schedule_id),
    CONSTRAINT uq_appt_queue          UNIQUE (schedule_id, appointment_date, queue_no),
    CONSTRAINT ck_appt_queue          CHECK (queue_no > 0),
    CONSTRAINT ck_appt_status         CHECK (status IN ('BOOKED','CONFIRMED','COMPLETED','CANCELLED','NO_SHOW'))
);

-- ---------------------------------------------------------------------
--  CONSULTATION  (1:1 with Appointment)
-- ---------------------------------------------------------------------
CREATE TABLE consultation (
    consultation_id     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    appointment_id      NUMBER        NOT NULL,
    consultation_date   DATE          DEFAULT SYSDATE NOT NULL,
    symptoms            VARCHAR2(500),
    diagnosis           VARCHAR2(500) NOT NULL,
    notes               VARCHAR2(500),
    follow_up_date      DATE,
    CONSTRAINT pk_consultation        PRIMARY KEY (consultation_id),
    CONSTRAINT fk_consult_appt        FOREIGN KEY (appointment_id) REFERENCES appointment (appointment_id),
    CONSTRAINT uq_consult_appt        UNIQUE (appointment_id),
    CONSTRAINT ck_consult_followup    CHECK (follow_up_date IS NULL OR follow_up_date > consultation_date)
);

-- ---------------------------------------------------------------------
--  PRESCRIPTION_ITEM
-- ---------------------------------------------------------------------
CREATE TABLE prescription_item (
    item_id             NUMBER GENERATED BY DEFAULT AS IDENTITY,
    consultation_id     NUMBER        NOT NULL,
    medicine_name       VARCHAR2(100) NOT NULL,
    dosage              VARCHAR2(30)  NOT NULL,
    frequency           VARCHAR2(30)  NOT NULL,
    duration_days       NUMBER(3)     NOT NULL,
    instructions        VARCHAR2(200),
    CONSTRAINT pk_prescription_item   PRIMARY KEY (item_id),
    CONSTRAINT fk_item_consult        FOREIGN KEY (consultation_id)
                                      REFERENCES consultation (consultation_id) ON DELETE CASCADE,
    CONSTRAINT ck_item_duration       CHECK (duration_days BETWEEN 1 AND 365)
);

-- ---------------------------------------------------------------------
--  PAYMENT  (1:1 with Appointment)
-- ---------------------------------------------------------------------
CREATE TABLE payment (
    payment_id          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    appointment_id      NUMBER        NOT NULL,
    amount              NUMBER(10,2)  NOT NULL,
    payment_method      VARCHAR2(10)  NOT NULL,
    payment_status      VARCHAR2(10)  DEFAULT 'PENDING' NOT NULL,
    payment_date        DATE,
    CONSTRAINT pk_payment             PRIMARY KEY (payment_id),
    CONSTRAINT fk_payment_appt        FOREIGN KEY (appointment_id) REFERENCES appointment (appointment_id),
    CONSTRAINT uq_payment_appt        UNIQUE (appointment_id),
    CONSTRAINT ck_payment_amount      CHECK (amount > 0),
    CONSTRAINT ck_payment_method      CHECK (payment_method IN ('CASH','CARD','ONLINE','INSURANCE')),
    CONSTRAINT ck_payment_status      CHECK (payment_status IN ('PENDING','PAID','REFUNDED','FAILED')),
    -- a settled payment must have a date
    CONSTRAINT ck_payment_date        CHECK (payment_status IN ('PENDING','FAILED') OR payment_date IS NOT NULL)
);

-- ---------------------------------------------------------------------
--  APPOINTMENT_AUDIT  (filled by a trigger on APPOINTMENT.status)
-- ---------------------------------------------------------------------
CREATE TABLE appointment_audit (
    audit_id            NUMBER GENERATED BY DEFAULT AS IDENTITY,
    appointment_id      NUMBER        NOT NULL,
    old_status          VARCHAR2(10),
    new_status          VARCHAR2(10)  NOT NULL,
    changed_by          VARCHAR2(30)  DEFAULT USER NOT NULL,
    changed_at          TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_appointment_audit   PRIMARY KEY (audit_id),
    CONSTRAINT fk_audit_appt          FOREIGN KEY (appointment_id)
                                      REFERENCES appointment (appointment_id) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------
--  ERROR_LOG  (written by PL/SQL exception handlers, autonomous transaction)
-- ---------------------------------------------------------------------
CREATE TABLE error_log (
    log_id              NUMBER GENERATED BY DEFAULT AS IDENTITY,
    source              VARCHAR2(100) NOT NULL,
    error_code          NUMBER,
    error_message       VARCHAR2(4000),
    logged_by           VARCHAR2(30)  DEFAULT USER NOT NULL,
    logged_at           TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_error_log           PRIMARY KEY (log_id)
);

-- ---------------------------------------------------------------------
--  Indexes on foreign keys / common search columns
-- ---------------------------------------------------------------------
CREATE INDEX ix_doctor_spec        ON doctor (specialization_id);
CREATE INDEX ix_schedule_doctor    ON doctor_schedule (doctor_id);
CREATE INDEX ix_schedule_hospital  ON doctor_schedule (hospital_id);
CREATE INDEX ix_appt_patient       ON appointment (patient_id);
CREATE INDEX ix_appt_date          ON appointment (appointment_date);
CREATE INDEX ix_item_consult       ON prescription_item (consultation_id);
CREATE INDEX ix_audit_appt         ON appointment_audit (appointment_id);
CREATE INDEX ix_hospital_city      ON hospital (city);
